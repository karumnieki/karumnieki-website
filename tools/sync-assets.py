"""sync-assets.py: bind site/img to the inventory ids. Run before every phase.

For each photo slot and size in slots.json: if photos/web/<id>-<role>-<size>.webp exists (the graded file)
it is copied into site/img; otherwise the ORIGINAL is transcoded under that same filename (no crop, no upscale,
WebP q82) so that the graded file later replaces it without any HTML change, and the id is listed in stand-ins.md.
Static files (logo mark, partner badges) are copied as-is. Usage: python sync-assets.py
"""
import io
import json
import os
import shutil
import sys
import time

from PIL import Image

# photos/ (the graded photo masters) is not in this repo. Stop before any
# write when it is missing, because with a partial photos/ folder this script would overwrite graded files.
if not os.path.isdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "photos", "web")):
    sys.exit("sync-assets.py: photos/web is not here. The photo masters are not in this repo; "
             "site/img already holds every file the page uses. Ask a maintainer for photo changes.")

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
PHOTOS = os.path.join(ROOT, "photos")
WEB = os.path.join(PHOTOS, "web")
IMG = os.path.join(ROOT, "site", "img")
STATE_PATH = os.path.join(HERE, "sync-state.json")
os.makedirs(IMG, exist_ok=True)

slots = json.load(io.open(os.path.join(HERE, "slots.json"), encoding="utf-8"))
state = json.load(io.open(STATE_PATH, encoding="utf-8")) if os.path.exists(STATE_PATH) else {}
new_state = {}
landed, web_ok, standins = [], [], {}


def sig(path):
    st = os.stat(path)
    return [st.st_size, int(st.st_mtime)]


def transcode(src, dst, long_edge):
    im = Image.open(src).convert("RGB")
    w, h = im.size
    longest = max(w, h)
    if longest > long_edge:
        r = long_edge / float(longest)
        im = im.resize((round(w * r), round(h * r)), Image.LANCZOS)
    im.save(dst, "WEBP", quality=82, method=6)
    return im.size


seen = set()
for p in slots["photos"]:
    for size in p["sizes"]:
        name = "%s-%s-%d.webp" % (p["id"], p["role"], size)
        if name in seen:
            continue
        seen.add(name)
        dst = os.path.join(IMG, name)
        src = os.path.join(WEB, name)
        if os.path.exists(src):
            s = sig(src)
            key = "web:" + name
            if state.get(key) != s or not os.path.exists(dst):
                shutil.copyfile(src, dst)
                landed.append(name)
            new_state[key] = s
            web_ok.append(name)
        else:
            orig = os.path.join(PHOTOS, p["original"])
            s = sig(orig)
            key = "standin:" + name
            if state.get(key) != s or not os.path.exists(dst):
                transcode(orig, dst, size)
            new_state[key] = s
            with Image.open(dst) as im:
                px = "%dx%d" % im.size
            standins.setdefault(p["id"], {"slot": p.get("slot", ""), "files": [], "defect": p.get("defect", "")})
            standins[p["id"]]["files"].append("%s (%s)" % (name, px))

for st in slots["static"]:
    src = os.path.join(PHOTOS, st["src"])
    dst = os.path.join(IMG, st["dst"])
    if not os.path.exists(src):
        print("MISSING static source:", st["src"])
        continue
    if not os.path.exists(dst) or sig(src) != sig(dst):
        shutil.copyfile(src, dst)

# "generated" holds files that tools/make-icons.py writes straight into site/img rather than copying
# from photos/. Without them here the prune below would delete the whole favicon set on the next sync.
expected = set(seen) | set(st["dst"] for st in slots["static"]) | set(slots.get("generated", []))
pruned = []
for f in os.listdir(IMG):
    if f not in expected and os.path.isfile(os.path.join(IMG, f)):
        os.remove(os.path.join(IMG, f))
        pruned.append(f)

json.dump(new_state, io.open(STATE_PATH, "w", encoding="utf-8"), indent=1)

lines = [
    "# Stand-ins still in site/img",
    "",
    "Generated by tools/sync-assets.py on %s. A stand-in is the unedited original transcoded under the final"
    % time.strftime("%Y-%m-%d %H:%M"),
    "filename; the graded web file replaces it on the next sync. **This table must be empty before the site",
    "goes to anyone.**",
    "",
    "| id | slot | files in site/img | what a guest would notice |",
    "|---|---|---|---|",
]
for fid in standins:
    d = standins[fid]
    lines.append("| %s | %s | %s | %s |" % (fid, d["slot"], ", ".join(d["files"]), d["defect"]))
if not standins:
    lines.append("| (none) | | | |")
io.open(os.path.join(HERE, "stand-ins.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

print("web assets bound: %d files" % len(web_ok))
print("stand-ins: %d ids -> %s" % (len(standins), ", ".join(standins) if standins else "none"))
print("copied or changed since last sync: %s" % (", ".join(landed) if landed else "none"))
print("pruned (no longer in slots.json): %s" % (", ".join(pruned) if pruned else "none"))
